const gate = (keys, extra = {}) => {
  // `word('SOL')` ya trae sus propias teclas y la palabra completa.
  if (keys && typeof keys === 'object' && !Array.isArray(keys) && keys.word) {
    return { ...keys, ...extra };
  }
  return {
    keys: Array.isArray(keys) ? keys : [keys],
    ...extra,
  };
};

const word = (valor) => ({
  keys: valor.split(''),
  word: valor,
});

/**
 * Un reto de frase o párrafo. `keys` conserva los caracteres para las
 * comprobaciones estructurales, pero el juego usa `paragraph` para permitir
 * escribir con espacios, tildes y puntuación.
 */
const paragraph = (texto) => ({
  paragraph: texto,
  keys: Array.from(texto),
});

