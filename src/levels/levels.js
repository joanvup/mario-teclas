export const LEVEL_BY_ID = Object.fromEntries(LEVELS.map((l) => [l.id, l]));

export function levelsOfWorld(worldId) {
  return LEVELS.filter((l) => l.world === worldId);
}

export function firstLevelOfWorld(worldId) {
  return LEVELS.find((l) => l.world === worldId && l.index === 1);
}

export function nextLevelId(levelId) {
  const i = LEVELS.findIndex((l) => l.id === levelId);
  return i >= 0 && i < LEVELS.length - 1 ? LEVELS[i + 1].id : null;
}
