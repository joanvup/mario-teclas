import { chromium } from '@playwright/test';

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('console', (msg) => {
  if (msg.type() === 'error') errors.push(`console: ${msg.text()}`);
});
page.on('pageerror', (err) => errors.push(`pageerror: ${err.message}`));
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
await page.locator('[data-action="title-start"]').click();
await page.locator('[data-action="play-next"]').click();
await page.waitForTimeout(300);
console.log('tutorial visible:', await page.locator('.tutorial-modal').isVisible());
await page.screenshot({ path: 'test-results/tutorial.png' });
await page.keyboard.press('ArrowRight');
await page.waitForTimeout(250);
await page.keyboard.press('ArrowLeft');
await page.waitForTimeout(250);
await page.keyboard.press('Space');
await page.waitForTimeout(250);
await page.screenshot({ path: 'test-results/tutorial-step4.png' });
await page.keyboard.press('a');
await page.waitForTimeout(500);
console.log('screen now:', await page.locator('h1').first().textContent());
console.log('intro keyboard keys:', await page.locator('#intro-keyboard .vkb__key').count());
await page.screenshot({ path: 'test-results/intro.png', fullPage: true });
await page.locator('[data-action="start-level"]').click();
await page.waitForTimeout(600);
console.log('canvas visible:', await page.locator('#game-canvas').isVisible());
console.log('hud:', await page.locator('#hud-name').textContent());
await page.screenshot({ path: 'test-results/game.png' });
await page.keyboard.down('ArrowRight');
await page.waitForTimeout(5000);
await page.keyboard.up('ArrowRight');
await page.waitForTimeout(500);
await page.screenshot({ path: 'test-results/game-after.png' });
console.log('state:', await page.evaluate(() => window.__TKA__.snapshot()));
console.log('errors:', errors);
await browser.close();
